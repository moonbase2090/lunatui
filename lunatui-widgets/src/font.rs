pub(super) fn rows(ch: char) -> &'static [u8; 8] {
    let ch = match ch {
        'a'..='z' => char::from(u8::try_from(u32::from(ch).wrapping_sub(32)).unwrap_or(b' ')),
        other => other,
    };
    let code = u32::from(ch);
    if (32..127).contains(&code) {
        let index = usize::try_from(code - 32).unwrap_or(0);
        &ROWS[index]
    } else {
        &ROWS[0]
    }
}
